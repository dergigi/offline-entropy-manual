const val SeedSafetyWarningLead =
    "Never use a seed generated by a website or an app, and never enter your seed into one. " +
        "Either can save it and steal your bitcoins."

private val SeedSafetyWarningPlainBullets = listOf(
    "Do not photograph your seed phrase.",
    "Do not read it aloud.",
    "Write it down on paper.",
    "Better yet, stamp it into steel.",
)

private val SeedSafetyWarningTrailingBullets = listOf(
    "Do your own research.",
    "Use at your own risk.",
)

@Composable
fun SeedSafetyWarning(
    onOpenBackup321: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val linkColor = MaterialTheme.colorScheme.error
    val backupRule = buildAnnotatedString {
        append("• Consider the ")
        withLink(
            LinkAnnotation.Clickable(
                tag = "backup-321",
                styles = TextLinkStyles(style = SpanStyle(color = linkColor)),
                linkInteractionListener = { onOpenBackup321() },
            ),
        ) {
            append("3-2-1 backup rule")
        }
        append(".")
    }

    Column(modifier = modifier) {
        Text(
            text = "Warning",
            style = MaterialTheme.typography.titleMedium,
            color = MaterialTheme.colorScheme.error,
        )
        Text(
            text = SeedSafetyWarningLead,
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.error,
            modifier = Modifier.padding(top = 8.dp),
        )
        Text(
            text = "In addition:",
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.error,
            modifier = Modifier.padding(top = 12.dp),
        )
        SeedSafetyWarningPlainBullets.forEach { point ->
            Text(
                text = "• $point",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.error,
                modifier = Modifier.padding(top = 6.dp, start = 4.dp),
            )
        }
        Text(
            text = backupRule,
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.error,
            modifier = Modifier.padding(top = 6.dp, start = 4.dp),
        )
        SeedSafetyWarningTrailingBullets.forEach { point ->
            Text(
                text = "• $point",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.error,
                modifier = Modifier.padding(top = 6.dp, start = 4.dp),
            )
        }
    }
}

@Composable
fun Bip39ChecksumNote(
    onOpenAirgappedDevice: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val linkColor = MaterialTheme.colorScheme.primary
    val note = buildAnnotatedString {
        append(
            "The last word of a BIP39 seed (the 12th or 24th) is a checksum. After you have " +
                "the first 11 or 23 words, calculate it on a hardware wallet that supports " +
                "that step, such as SeedSigner, BitBox02, or Blockstream Jade, or on some " +
                "other ",
        )
        withLink(
            LinkAnnotation.Clickable(
                tag = "airgapped-device",
                styles = TextLinkStyles(style = SpanStyle(color = linkColor)),
                linkInteractionListener = { onOpenAirgappedDevice() },
            ),
        ) {
            append("airgapped device")
        }
        append(". Do not use a website or phone app.")
    }

    Column(modifier = modifier) {
        Text(
            text = "Checksum",
            style = MaterialTheme.typography.titleMedium,
        )
        Text(
            text = note,
            style = MaterialTheme.typography.bodyMedium,
            modifier = Modifier.padding(top = 8.dp),
        )
    }
}

@Composable
fun AppVersionFooter(modifier: Modifier = Modifier) {
    val context = LocalContext.current
    val muted = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.55f)
    val linkColor = MaterialTheme.colorScheme.primary.copy(alpha = 0.75f)
    val releasesUrl = "https://github.com/dergigi/offline-entropy-manual/releases"
    val commitUrl =
        "https://github.com/dergigi/offline-entropy-manual/commit/${BuildConfig.GIT_HASH}"
    val label = buildAnnotatedString {
        withLink(
            LinkAnnotation.Clickable(
                tag = "version",
                styles = TextLinkStyles(style = SpanStyle(color = linkColor)),
                linkInteractionListener = { openUrl(context, releasesUrl) },
            ),
        ) {
            append("v${BuildConfig.VERSION_NAME}")
        }
        append(" · ")
        withLink(
            LinkAnnotation.Clickable(
                tag = "git-hash",
                styles = TextLinkStyles(style = SpanStyle(color = linkColor)),
                linkInteractionListener = { openUrl(context, commitUrl) },
            ),
        ) {
            append(BuildConfig.GIT_HASH)
        }
    }

    Text(
        text = label,
        style = MaterialTheme.typography.labelSmall.copy(color = muted),
        textAlign = TextAlign.Center,
        modifier = modifier.fillMaxWidth(),
    )
}

@Composable
fun SafetyFooter(
    onOpenAirgappedDevice: () -> Unit,
    onOpenBackup321: () -> Unit,
    modifier: Modifier = Modifier,
) {
    Column(modifier = modifier) {
        SeedSafetyWarning(onOpenBackup321 = onOpenBackup321)
        Bip39ChecksumNote(
            onOpenAirgappedDevice = onOpenAirgappedDevice,
            modifier = Modifier.padding(top = 24.dp),
        )
        AppVersionFooter(modifier = Modifier.padding(top = 32.dp))
    }
}
